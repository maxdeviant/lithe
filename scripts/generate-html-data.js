// Writes `Lithe/Syntax/HtmlData.lean` from web standards data, for the macro to check markup against.

import { writeFileSync } from "node:fs";
import { htmlElementAttributes } from "html-element-attributes";
import { htmlEventAttributes } from "html-event-attributes";
import { htmlTagNames } from "html-tag-names";
import { htmlVoidElements } from "html-void-elements";

const list = (names) => `[${[...names].sort().map((n) => JSON.stringify(n)).join(", ")}]`;

const elementAttributes = Object.entries(htmlElementAttributes)
  .filter(([tag]) => tag !== "*")
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([tag, attrs]) => `  (${JSON.stringify(tag)}, ${list(attrs)})`)
  .join(",\n");

const output = `module

/-!
Web standards data for checking markup. Generated by \`scripts/generate-html-data.js\`, so don't edit
it by hand.
-/

public meta section

namespace Lithe.HtmlData

/-- The HTML element names. -/
def tagNames : List String :=
  ${list(htmlTagNames)}

/-- The HTML elements that have no closing tag and no children. -/
def voidElements : List String :=
  ${list(htmlVoidElements)}

/-- The attributes that every HTML element accepts. -/
def globalAttributes : List String :=
  ${list(htmlElementAttributes["*"])}

/-- The event handler attributes, such as \`onclick\`. -/
def eventAttributes : List String :=
  ${list(htmlEventAttributes)}

/-- The attributes that are specific to each HTML element. -/
def elementAttributes : List (String × List String) := [
${elementAttributes}
]

end Lithe.HtmlData
`;

writeFileSync(new URL("../Lithe/Syntax/HtmlData.lean", import.meta.url), output);
