// Writes `src/Lithe/Syntax/HtmlData.lean` from web standards data, for the macro to check markup against.

import { writeFileSync } from "node:fs";
import { htmlElementAttributes } from "html-element-attributes";
import { htmlEventAttributes } from "html-event-attributes";
import { htmlTagNames } from "html-tag-names";
import { htmlVoidElements } from "html-void-elements";
import { svgElementAttributes } from "svg-element-attributes";
import { svgTagNames } from "svg-tag-names";

const list = (names) => `[${[...names].sort().map((n) => JSON.stringify(n)).join(", ")}]`;

const perElement = (table) =>
  Object.entries(table)
    .filter(([tag]) => tag !== "*")
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([tag, attrs]) => `  (${JSON.stringify(tag)}, ${list(attrs)})`)
    .join(",\n");

// The media elements only work in the HTML namespace, and the HTML parser leaves SVG for `font` if it
// has certain attributes, so all of these belong in `foreignObject` if they are used at all.
const notInSvg = ["audio", "canvas", "font", "iframe", "video"];

// Open Graph's `property` comes from RDFa, which the standards data leaves out.
const elementAttributes = {
  ...htmlElementAttributes,
  meta: [...htmlElementAttributes.meta, "property"],
};

const output = `module

/-!
Web standards data for checking markup. Generated by \`scripts/generate-html-data.js\`, so don't edit
it by hand.
-/

public meta section

namespace Lithe.HtmlData

/-- The HTML element names. -/
def tagNames : List String :=
  ${list(htmlTagNames)}

/-- The HTML elements that have no closing tag and no children. -/
def voidElements : List String :=
  ${list(htmlVoidElements)}

/-- The attributes that every HTML element accepts. -/
def globalAttributes : List String :=
  ${list(htmlElementAttributes["*"])}

/-- The event handler attributes, such as \`onclick\`. -/
def eventAttributes : List String :=
  ${list(htmlEventAttributes)}

/-- The attributes that are specific to each HTML element. -/
def elementAttributes : List (String × List String) := [
${perElement(elementAttributes)}
]

/-- The SVG element names, which are case-sensitive. -/
def svgTagNames : List String :=
  ${list(svgTagNames.filter((tag) => !notInSvg.includes(tag)))}

/-- The attributes that every SVG element accepts. -/
def svgGlobalAttributes : List String :=
  ${list(svgElementAttributes["*"])}

/-- The attributes that are specific to each SVG element. -/
def svgElementAttributes : List (String × List String) := [
${perElement(svgElementAttributes)}
]

end Lithe.HtmlData
`;

writeFileSync(new URL("../src/Lithe/Syntax/HtmlData.lean", import.meta.url), output);
